NOT_SPECIFIED = "не указано"


def _celebration_block(data: dict) -> str:
    def v(key: str) -> str:
        value = data.get(key)
        return str(value).strip() if value not in (None, "") else NOT_SPECIFIED

    return f"""ИНФОРМАЦИЯ О ПРАЗДНИКЕ:

Роль заказчика: {v("client_role")}
Событие: {v("event")}
Возраст виновника торжества: {v("celebrant_age")}
Тема: {v("theme")}
Гости: {v("guests")}
Место: {v("location")}
Бюджет: {v("budget")}
Пожелания: {v("wishes")}
Опасения: {v("concerns")}
Критерии успеха: {v("success_criteria")}
"""


def client_portrait_prompt(data: dict) -> str:
    return f"""
Ты — интеграционный профессор и эксперт по анализу
клиентского опыта в сфере организации праздников.

Твоя задача — создать эмоциональный портрет заказчика
на основе предоставленной информации.

ВАЖНО:
1. Не ставь психологических диагнозов.
2. Не утверждай скрытые мотивы как факты.
3. Разделяй факты, интерпретации и гипотезы.
4. Не используй шаблонные характеристики личности.
5. Анализируй человеческую потребность, стоящую за заказом.
6. Если поле "не указано" — не додумывай его, а отметь, что информации нет.

{_celebration_block(data)}
СОЗДАЙ ЭМОЦИОНАЛЬНЫЙ ПОРТРЕТ:

1. ФАКТЫ
Что заказчик прямо сообщил.

2. ЭМОЦИОНАЛЬНАЯ ПОТРЕБНОСТЬ
Что для него может быть эмоционально важно.

3. ЖЕЛАЕМЫЙ РЕЗУЛЬТАТ
Какие чувства он хочет испытать сам
и какие чувства хочет вызвать у гостей.

4. СТРАХИ И ОПАСЕНИЯ
Что может испортить впечатление от праздника.

5. СОЦИАЛЬНЫЙ ОБРАЗ
Как заказчик хочет выглядеть в глазах окружающих.
Укажи, если это только гипотеза.

6. КРИТЕРИИ УСПЕХА
По каким признакам заказчик поймет,
что праздник получился.

7. РЕКОМЕНДАЦИИ ОРГАНИЗАТОРУ
Как общаться с заказчиком.
Что предложить.
На чем нельзя экономить внимание.

8. ГЛАВНАЯ ЭМОЦИОНАЛЬНАЯ ФОРМУЛА
Закончи одним предложением:
"На самом деле заказчик хочет не просто ...,
а хочет почувствовать ..."

Пиши на русском языке.
Будь конкретным, деликатным и практичным.
"""


def concepts_prompt(data: dict) -> str:
    return f"""
На основе ИНФОРМАЦИИ О ПРАЗДНИКЕ создай 3 индивидуальные концепции праздника:
Бюджетная — интересный праздник с минимальными затратами.
Оптимальная — баланс стоимости, качества и развлечений.
Премиальная — максимально яркие впечатления с дополнительными услугами.

Для каждой концепции укажи:
Название праздника.
Основную идею и тематику.
Оформление.
Развлечения и активности.
Краткий сценарий.
Продолжительность.
Примерную стоимость.

Все предложения должны учитывать возраст детей, бюджет и пожелания клиента.
Не представляй вымышленные цены как реальные.
Не придумывай ответы за клиента; если данных нет — так и скажи.
Объясняй, почему предложенная концепция ему подходит.
Пиши на русском языке.

{_celebration_block(data)}
"""
